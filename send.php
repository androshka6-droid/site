<?php
if ($_SERVER["REQUEST_METHOD"] == "POST") {
    // =========================================================================
    // НАСТРОЙКИ: Пожалуйста, измените эти значения
    // =========================================================================

    // ВАШ EMAIL АДРЕС
    // Сюда будут приходить письма с формы
    $recipient_email = "sales@deansautosales.com"; // <--- ЗАМЕНИТЕ НА ВАШ EMAIL

    // ТЕМА ПИСЬМА
    // Вы можете изменить тему письма, которое будет приходить вам
    $subject = "Новое сообщение с сайта Dean's Auto Sales";

    // СТРАНИЦА "СПАСИБО"
    // URL, куда будет перенаправлен пользователь после успешной отправки
    $thank_you_page = "thank-you.html";

    // =========================================================================
    // Сбор и очистка данных из формы
    // =========================================================================

    $name = isset($_POST['name']) ? strip_tags(trim($_POST['name'])) : '';
    $email = isset($_POST['email']) ? filter_var(trim($_POST['email']), FILTER_SANITIZE_EMAIL) : '';
    $phone = isset($_POST['phone']) ? strip_tags(trim($_POST['phone'])) : '';
    $message = isset($_POST['message']) ? strip_tags(trim($_POST['message'])) : '';

    // =========================================================================
    // Проверка на заполненность обязательных полей
    // =========================================================================

    if (empty($name) || empty($message) || !filter_var($email, FILTER_VALIDATE_EMAIL)) {
        // Если обязательные поля не заполнены, прерываем выполнение
        http_response_code(400);
        echo "Пожалуйста, заполните все обязательные поля.";
        exit;
    }

    // =========================================================================
    // Формирование тела письма
    // =========================================================================

    $email_content = "Имя: $name\n";
    $email_content .= "Email: $email\n";
    if (!empty($phone)) {
        $email_content .= "Телефон: $phone\n";
    }
    $email_content .= "\nСообщение:\n$message\n";

    // =========================================================================
    // Формирование заголовков письма
    // =========================================================================

    $email_headers = "From: $name <$email>\r\n";
    $email_headers .= "Reply-To: $email\r\n";
    $email_headers .= "Content-Type: text/plain; charset=UTF-8\r\n";
    $email_headers .= "X-Mailer: PHP/" . phpversion();

    // =========================================================================
    // ВАЖНО: Настройка для Titan Mail (или другого SMTP)
    // =========================================================================
    //
    // Стандартная функция mail() может не работать на многих хостингах или
    // письма могут попадать в спам. Для надежной отправки через Titan Mail
    // вам понадобится использовать SMTP.
    //
    // 1. Убедитесь, что ваш хостинг поддерживает отправку через внешний SMTP.
    // 2. Вам нужно будет указать настройки SMTP в файле php.ini на вашем сервере.
    //
    // Пример настроек для php.ini:
    //
    // [mail function]
    // SMTP = smtp.titan.email
    // smtp_port = 465
    // sendmail_from = "sales@deansautosales.com" ; <--- ВАШ EMAIL
    // auth_username = "sales@deansautosales.com" ; <--- ВАШ ЛОГИН
    // auth_password = "YOUR_PASSWORD"          ; <--- ВАШ ПАРОЛЬ
    //
    // Если вы не можете редактировать php.ini, лучшим решением будет
    // использовать библиотеку PHPMailer, которая позволяет указать
    // SMTP настройки прямо в коде.
    //
    // =========================================================================

    // Отправка письма
    if (mail($recipient_email, $subject, $email_content, $email_headers)) {
        // Если письмо отправлено успешно, перенаправляем на страницу "Спасибо"
        header("Location: $thank_you_page");
    } else {
        // Если возникла ошибка
        http_response_code(500);
        echo "К сожалению, произошла ошибка при отправке сообщения.";
    }

} else {
    // Если кто-то пытается зайти на этот файл напрямую
    http_response_code(403);
    echo "Доступ запрещен.";
}
?>
